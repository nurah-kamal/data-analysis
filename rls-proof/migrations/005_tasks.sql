-- The foreign key includes tenant_id, so a task can only point at a project
-- in its own tenant, whoever writes it.
create table tasks (
  id         integer generated by default as identity primary key,
  tenant_id  integer not null default app_current_tenant(),
  project_id integer not null,
  title      text not null,
  done       boolean not null default false,
  foreign key (tenant_id, project_id) references projects (tenant_id, id)
);

create index tasks_tenant_id on tasks (tenant_id);
